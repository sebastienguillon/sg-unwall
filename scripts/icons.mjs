// Renders assets/icon.svg to the PNG sizes the manifest uses, in src/icons/,
// and to the website icon, docs/icon.png.
//   pnpm icons
import { chromium } from "playwright";
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import { crc32 } from "node:zlib";

// Each PNG records where it comes from, in a tEXt chunk Impeccable's
// `embed-prompt --read` understands.
const ORIGIN =
  "Origin: rendered from assets/icon.svg (hand-written SVG) by scripts/icons.mjs, a Playwright Chromium screenshot; not generated by an image model.";

function withText(png, keyword, text) {
  const type = Buffer.from("tEXt", "latin1");
  const data = Buffer.concat([
    Buffer.from(keyword, "latin1"),
    Buffer.from([0]),
    Buffer.from(text, "latin1"),
  ]);
  const length = Buffer.alloc(4);
  length.writeUInt32BE(data.length);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(Buffer.concat([type, data])));
  const iend = png.length - 12; // IEND is always the last, empty chunk
  return Buffer.concat([png.subarray(0, iend), length, type, data, crc, png.subarray(iend)]);
}

const root = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const svg = await readFile(join(root, "assets/icon.svg"), "utf8");
const outputs = [
  ...[16, 32, 48, 128].map((size) => [size, join(root, `src/icons/icon-${size}.png`)]),
  [256, join(root, "docs/icon.png")],
];
const browser = await chromium.launch();
for (const [size, path] of outputs) {
  const page = await browser.newPage({ viewport: { width: size, height: size } });
  await page.setContent(
    `<style>html,body{margin:0;background:transparent}svg{display:block;width:${size}px;height:${size}px}</style>${svg}`,
  );
  const png = await page.screenshot({ omitBackground: true });
  await writeFile(path, withText(png, "impeccable:prompt", ORIGIN));
  await page.close();
}
await browser.close();
